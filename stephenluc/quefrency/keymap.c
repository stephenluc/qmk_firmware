bool encoder_update_user(uint8_t index, bool clockwise) {
    // Left encoder
    if (index == 0) {
        if (clockwise) {
            tap_code(KC_VOLU);
        } else {
            tap_code(KC_VOLD);
        }
    }
    return false;
}

bool process_record_user(uint16_t keycode, keyrecord_t *record)
{
  switch (keycode) {
    case WHOAMI:
      if (record->event.pressed) {
        SEND_STRING("Property of Stephen Luc (@stephenluc)");
      }
      return false;
    case SECRET:
      if (record->event.pressed) {
        SEND_STRING("secret");
      }
      return false;
    default:
    return true;
  }
}
